BEGIN;

CREATE TABLE companion_regions (
  region_key TEXT PRIMARY KEY CHECK (region_key ~ '^[a-z][a-z0-9_]*$'),
  display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
  visibility TEXT NOT NULL CHECK (visibility IN ('public', 'discovery_locked')),
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE companion_species_catalog (
  species_key TEXT PRIMARY KEY CHECK (species_key ~ '^[a-z][a-z0-9_]*$'),
  display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
  region_key TEXT NOT NULL REFERENCES companion_regions(region_key) ON UPDATE RESTRICT ON DELETE RESTRICT,
  element TEXT NOT NULL CHECK (element IN ('eau', 'feu', 'electrique', 'terre', 'air', 'magie', 'psy', 'ombre')),
  editorial_status TEXT NOT NULL DEFAULT 'draft' CHECK (editorial_status IN ('draft', 'approved')),
  availability_status TEXT NOT NULL DEFAULT 'unavailable'
    CHECK (availability_status IN ('unavailable', 'discoverable', 'available', 'retired')),
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT companion_species_not_available_unapproved
    CHECK (editorial_status = 'approved' OR availability_status = 'unavailable')
);

CREATE INDEX companion_species_region_idx
  ON companion_species_catalog(region_key, species_key);
CREATE INDEX companion_species_visibility_idx
  ON companion_species_catalog(editorial_status, availability_status, region_key);

CREATE TABLE companion_species_forms (
  species_key TEXT NOT NULL REFERENCES companion_species_catalog(species_key) ON UPDATE CASCADE ON DELETE RESTRICT,
  form_key TEXT NOT NULL CHECK (form_key ~ '^[a-z][a-z0-9_]*$'),
  display_name TEXT NOT NULL CHECK (length(btrim(display_name)) > 0),
  form_order INTEGER NOT NULL CHECK (form_order >= 0),
  PRIMARY KEY (species_key, form_key),
  UNIQUE (species_key, form_order)
);

CREATE TABLE companion_species_admin_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_account_id UUID REFERENCES accounts(id) ON DELETE SET NULL,
  action TEXT NOT NULL CHECK (action IN (
    'region_created', 'region_updated', 'species_created', 'species_updated',
    'species_availability_changed', 'species_retired', 'form_created', 'form_updated'
  )),
  entity_type TEXT NOT NULL CHECK (entity_type IN ('region', 'species', 'form')),
  entity_key TEXT NOT NULL CHECK (length(btrim(entity_key)) > 0),
  revision INTEGER NOT NULL CHECK (revision > 0),
  before_state JSONB,
  after_state JSONB NOT NULL CHECK (jsonb_typeof(after_state) = 'object'),
  idempotency_key UUID UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX companion_species_admin_events_entity_idx
  ON companion_species_admin_events(entity_type, entity_key, created_at DESC);
CREATE INDEX companion_species_admin_events_actor_idx
  ON companion_species_admin_events(actor_account_id, created_at DESC);

